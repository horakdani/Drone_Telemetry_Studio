"""Draws the logo, the social preview card and the website's flight-trace backdrop.

The backdrop is not decoration for its own sake: it is the showcase flight itself
(scripts/generate_showcase.py), drawn the way a flight log would show it. The dashed
line is the ground track, the amber line is the drone at its real altitude above it,
and the drop lines connect the two.

Run after scripts/generate_showcase.py, which produces hud-preview.png:

    PYTHONPATH=src .venv/bin/python scripts/generate_brand_assets.py
"""

from __future__ import annotations

from pathlib import Path

import math

from PIL import Image, ImageDraw, ImageFilter

from drone_telemetry_studio.overlay.renderer import _font
from generate_showcase import DURATION_S, WAYPOINTS, _altitude, _progress, _route

ROOT = Path(__file__).parents[1]
IMAGES = ROOT / "docs/images"
BG = (7, 11, 16)
ACCENT = (55, 226, 196)
AMBER = (255, 181, 71)
TEXT = (230, 238, 245)
MUTED = (141, 162, 181)


def draw_mark(size: int) -> Image.Image:
    """Crosshair reticle with an amber centre, drawn at 4x and downsampled."""
    s = size * 4
    image = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((0, 0, s - 1, s - 1), radius=s // 4.5, fill=(13, 20, 28, 255))
    c, r, w = s / 2, s * 0.32, max(4, s // 22)
    draw.ellipse((c - r, c - r, c + r, c + r), outline=ACCENT, width=w)
    tick = s * 0.13
    for x0, y0, x1, y1 in (
        (c, c - r - tick * 0.4, c, c - r + tick),
        (c, c + r - tick, c, c + r + tick * 0.4),
        (c - r - tick * 0.4, c, c - r + tick, c),
        (c + r - tick, c, c + r + tick * 0.4, c),
    ):
        draw.line((x0, y0, x1, y1), fill=ACCENT, width=w)
    dot = s * 0.07
    draw.ellipse((c - dot, c - dot, c + dot, c + dot), fill=AMBER)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def flight_samples(step_s: float = 1.0) -> list[tuple[float, float, float, float]]:
    """(t, along_m, across_m, altitude_m) of the showcase flight, start→end along +x."""
    curve, cumulative = _route()
    lat0 = math.radians(WAYPOINTS[0][0])
    local = [((lon - curve[0][1]) * 111_320 * math.cos(lat0), (lat - curve[0][0]) * 111_320) for lat, lon in curve]
    angle = math.atan2(local[-1][1], local[-1][0])
    cos_a, sin_a = math.cos(-angle), math.sin(-angle)
    total = cumulative[-1]
    samples, index = [], 1
    for k in range(int(DURATION_S / step_s) + 1):
        t = k * step_s
        d = _progress(t) * total
        while index < len(cumulative) - 1 and cumulative[index] < d:
            index += 1
        f = (d - cumulative[index - 1]) / max(1e-9, cumulative[index] - cumulative[index - 1])
        (ax, ay), (bx, by) = local[index - 1], local[index]
        x, y = ax + (bx - ax) * f, ay + (by - ay) * f
        samples.append((t, x * cos_a - y * sin_a, x * sin_a + y * cos_a, _altitude(t)))
    return samples


def trace_layout(width: float, margin: float, ground_y: float, lift: float, sag: float = 1.0):
    """Maps flight samples to (t, ground_xy, air_xy, altitude) on a canvas of the given width.

    The route is drawn at true scale along the flight; sag scales the sideways bend.
    """
    samples = flight_samples()
    length = samples[-1][1]
    scale = (width - 2 * margin) / length
    points = []
    for t, along, across, alt in samples:
        gx = margin + along * scale
        gy = ground_y + across * scale * sag
        points.append((t, (gx, gy), (gx, gy - alt * lift), alt))
    return points


def flight_trace_svg(width: int = 1600, height: int = 520) -> str:
    pts = trace_layout(width, margin=90, ground_y=280, lift=1.5)
    fmt = lambda xy: f"{xy[0]:.1f},{xy[1]:.1f}"
    ground = " ".join(fmt(g) for _, g, _, _ in pts)
    air = " ".join(fmt(a) for _, _, a, _ in pts)
    drops = "".join(
        f'<line x1="{a[0]:.1f}" y1="{a[1]:.1f}" x2="{g[0]:.1f}" y2="{g[1]:.1f}"/>' for t, g, a, _ in pts if t % 3 == 0
    )
    dots = "".join(f'<circle cx="{a[0]:.1f}" cy="{a[1]:.1f}" r="1.7"/>' for _, _, a, _ in pts)
    labels = []
    for t, g, a, alt in pts:
        if t and t % 30 == 0:
            labels.append(
                f'<line x1="{a[0]:.1f}" y1="{a[1] - 8:.1f}" x2="{a[0]:.1f}" y2="{a[1] - 30:.1f}" class="tick"/>'
                f'<text x="{a[0] + 6:.1f}" y="{a[1] - 22:.1f}">T+{int(t) // 60:02d}:{int(t) % 60:02d}</text>'
                f'<text x="{a[0] + 6:.1f}" y="{a[1] - 9:.1f}" class="alt">{alt:.0f} m</text>'
            )
    (_, home, _, _), (_, _, last, _) = pts[0], pts[-1]
    lat, lon = WAYPOINTS[0]
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" preserveAspectRatio="xMidYMax slice">
<!-- Generated by scripts/generate_brand_assets.py from the showcase flight. -->
<style>
text {{ font: 500 12px "JetBrains Mono", ui-monospace, Menlo, monospace; fill: #8da2b5; }}
text.alt {{ fill: #ffb547; }}
.tick {{ stroke: #8da2b5; stroke-opacity: .5; }}
</style>
<polyline points="{ground}" fill="none" stroke="#8da2b5" stroke-opacity=".35" stroke-width="1.2" stroke-dasharray="2 6"/>
<g stroke="#ffb547" stroke-opacity=".16" stroke-width="1">{drops}</g>
<polyline points="{air}" fill="none" stroke="#ffb547" stroke-opacity=".7" stroke-width="1.6"/>
<g fill="#ffb547" fill-opacity=".55">{dots}</g>
{"".join(labels)}
<circle cx="{home[0]:.1f}" cy="{home[1]:.1f}" r="9" fill="none" stroke="#8da2b5" stroke-opacity=".6"/>
<text x="{home[0]:.1f}" y="{home[1] + 4:.1f}" text-anchor="middle">H</text>
<text x="{home[0] - 4:.1f}" y="{home[1] + 30:.1f}">{lat:.4f}° N  {lon:.4f}° E</text>
<circle cx="{last[0]:.1f}" cy="{last[1]:.1f}" r="5" fill="#ffb547"/>
<circle cx="{last[0]:.1f}" cy="{last[1]:.1f}" r="12" fill="none" stroke="#ffb547" stroke-opacity=".5"/>
</svg>
"""


def draw_trace(card: Image.Image, box: tuple[int, int, int, int]) -> None:
    """The same flight trace as the website backdrop, rasterised into box."""
    left, top, right, bottom = box
    s = 2  # supersample
    w, h = (right - left) * s, (bottom - top) * s
    layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    pts = trace_layout(w, margin=40 * s, ground_y=h - 86 * s, lift=0.5 * s, sag=0.42)
    for t, g, a, _ in pts:
        if t % 3 == 0:
            draw.line((*a, *g), fill=(*AMBER, 40), width=s)
    for (_, g0, _, _), (t1, g1, _, _) in zip(pts, pts[1:]):
        if int(t1) % 4 < 2:
            draw.line((*g0, *g1), fill=(*MUTED, 90), width=s)
    draw.line([a for _, _, a, _ in pts], fill=(*AMBER, 170), width=2 * s, joint="curve")
    for _, _, (x, y), _ in pts:
        draw.ellipse((x - 2 * s, y - 2 * s, x + 2 * s, y + 2 * s), fill=(*AMBER, 140))
    hx, hy = pts[0][1]
    draw.ellipse((hx - 9 * s, hy - 9 * s, hx + 9 * s, hy + 9 * s), outline=(*MUTED, 150), width=s)
    draw.text((hx, hy), "H", font=_font(11 * s, bold=True), fill=(*MUTED, 200), anchor="mm")
    layer = layer.resize((right - left, bottom - top), Image.Resampling.LANCZOS)
    card.paste(layer, (left, top), layer)


def social_preview(hud: Path) -> Image.Image:
    width, height = 1280, 640
    card = Image.new("RGB", (width, height), BG)
    glow = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse((-300, 470, 1500, 1000), fill=(*AMBER, 34))
    glow = glow.filter(ImageFilter.GaussianBlur(110))
    card.paste(glow, (0, 0), glow)
    draw_trace(card, (0, 400, width, height))

    card.paste(draw_mark(84), (64, 70), draw_mark(84))
    draw = ImageDraw.Draw(card, "RGBA")
    draw.text((64, 186), "Drone Telemetry", font=_font(60, bold=True), fill=TEXT)
    draw.text((64, 254), "Studio", font=_font(60, bold=True), fill=ACCENT)
    body = _font(27)
    for i, line in enumerate((
        "Burn DJI flight data and a live route",
        "map onto your drone videos.",
    )):
        draw.text((64, 368 + i * 38), line, font=body, fill=MUTED)
    chip_font = _font(21, bold=True)
    x = 64
    for chip in ("Free & open source", "macOS", "100% local"):
        w = draw.textlength(chip, font=chip_font) + 32
        draw.rounded_rectangle((x, 480, x + w, 522), radius=21, outline=(31, 45, 58), width=2, fill=(13, 20, 28))
        draw.text((x + 16, 501), chip, font=chip_font, fill=TEXT, anchor="lm")
        x += w + 12

    if hud.exists():
        shot = Image.open(hud).convert("RGB")
        shot_w = 570
        shot = shot.resize((shot_w, round(shot.height * shot_w / shot.width)), Image.Resampling.LANCZOS)
        left, top = width - shot_w - 56, (height - shot.height) // 2
        shadow = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        ImageDraw.Draw(shadow).rounded_rectangle(
            (left - 6, top + 18, left + shot_w + 6, top + shot.height + 30), radius=22, fill=(0, 0, 0, 200)
        )
        card.paste(shadow.filter(ImageFilter.GaussianBlur(24)), (0, 0), shadow.filter(ImageFilter.GaussianBlur(24)))
        mask = Image.new("L", shot.size, 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, shot.width - 1, shot.height - 1), radius=16, fill=255)
        card.paste(shot, (left, top), mask)
        ImageDraw.Draw(card).rounded_rectangle(
            (left, top, left + shot.width - 1, top + shot.height - 1), radius=16, outline=(31, 45, 58), width=2
        )
    return card


def main() -> None:
    IMAGES.mkdir(parents=True, exist_ok=True)
    draw_mark(256).save(IMAGES / "logo.png")
    social_preview(IMAGES / "hud-preview.png").save(IMAGES / "social-preview.png", optimize=True)
    (ROOT / "site/flight-trace.svg").write_text(flight_trace_svg(), encoding="utf-8")
    for path in (IMAGES / "logo.png", IMAGES / "social-preview.png", ROOT / "site/flight-trace.svg"):
        print(path)


if __name__ == "__main__":
    main()
